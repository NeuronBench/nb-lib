"""Train a small handwritten-digit classifier and export it for nb-lib.

    uv run --with onnx --with numpy --with scikit-learn python -I models/make_digits.py

Uses scikit-learn's bundled 8x8 digits (a downsampled MNIST cousin, no
download needed). Writes:

- models/digits_mlp.onnx: pixels [1, 64] in [0, 1] -> probs [1, 10]
- models/digit_samples.ncl: held-out test images with their labels

Deterministic; rerun after editing and commit the outputs.
"""

import pathlib

import numpy as np
import onnx
from onnx import TensorProto, helper, numpy_helper
from sklearn.datasets import load_digits
from sklearn.neural_network import MLPClassifier

OUT = pathlib.Path(__file__).resolve().parent
HIDDEN = 32
SAMPLES_PER_DIGIT = 2

digits = load_digits()
x = (digits.data / 16.0).astype(np.float32)
y = digits.target

# Hold out the last few examples of each digit as the demo's samples.
held = []
for d in range(10):
    held += list(np.flatnonzero(y == d)[-SAMPLES_PER_DIGIT:])
held = sorted(held, key=lambda i: (y[i], i))
train = np.setdiff1d(np.arange(len(y)), held)

clf = MLPClassifier(hidden_layer_sizes=(HIDDEN,), max_iter=2000, random_state=0)
clf.fit(x[train], y[train])
print(f"train accuracy {clf.score(x[train], y[train]):.3f}, held-out {clf.score(x[held], y[held]):.3f}")


def const(name, array):
    return numpy_helper.from_array(np.asarray(array), name)


w1, w2 = (c.astype(np.float32) for c in clf.coefs_)
b1, b2 = (b.astype(np.float32)[None, :] for b in clf.intercepts_)
nodes = [
    # Reshape to the 8x8 image and back, so the Models window draws the digit.
    helper.make_node("Reshape", ["pixels", "image_shape"], ["image"], name="image"),
    helper.make_node("Reshape", ["image", "flat_shape"], ["flat"], name="flat"),
    helper.make_node("Gemm", ["flat", "w1", "b1"], ["hidden_pre"], name="hidden_pre"),
    helper.make_node("Relu", ["hidden_pre"], ["hidden"], name="hidden"),
    helper.make_node("Gemm", ["hidden", "w2", "b2"], ["logits"], name="logits"),
    helper.make_node("Softmax", ["logits"], ["probs"], name="probs", axis=1),
]
graph = helper.make_graph(
    nodes,
    "digits_mlp",
    [helper.make_tensor_value_info("pixels", TensorProto.FLOAT, [1, 64])],
    [helper.make_tensor_value_info("probs", TensorProto.FLOAT, [1, 10])],
    initializer=[
        const("image_shape", np.array([8, 8], dtype=np.int64)),
        const("flat_shape", np.array([1, 64], dtype=np.int64)),
        const("w1", w1),
        const("b1", b1),
        const("w2", w2),
        const("b2", b2),
    ],
    doc_string="8x8 digit classifier (scikit-learn digits): probs = softmax(relu(pixels W1 + b1) W2 + b2).",
)
model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 17)])
model.ir_version = 8
onnx.checker.check_model(model, full_check=True)
onnx.save(model, OUT / "digits_mlp.onnx")

# The exported graph must agree with scikit-learn.
from onnx.reference import ReferenceEvaluator  # noqa: E402

ref = ReferenceEvaluator(model)
for i in held:
    (probs,) = ref.run(None, {"pixels": x[i : i + 1]})
    np.testing.assert_allclose(probs[0], clf.predict_proba(x[i : i + 1])[0], rtol=1e-4, atol=1e-5)


def fmt(v):
    return f"{v:.4g}"


lines = [
    "# GENERATED by models/make_digits.py: held-out 8x8 digits, pixels in [0, 1],",
    "# row-major, with their labels and the model's prediction.",
    "[",
]
for i in held:
    pixels = ", ".join(fmt(v) for v in x[i])
    predicted = int(clf.predict(x[i : i + 1])[0])
    lines.append(f"  {{ label = {y[i]}, predicted = {predicted}, pixels = [{pixels}] }},")
lines.append("]")
(OUT / "digit_samples.ncl").write_text("\n".join(lines) + "\n")
print(f"wrote {len(held)} samples")

# Streams for teaching realistic neurons (demos/digits_transfer.ncl): a
# training stream and a separate test stream drawn from the model's
# training images, shuffled, each with the label and the model's answer.
# The hidden layer's largest value sets the scale for its target rates.
STREAM_TRAIN, STREAM_TEST = 300, 100
rng = np.random.default_rng(0)
order = rng.permutation(train)
hidden_max = float(np.maximum(x[train] @ w1 + b1, 0).max())


def stream(indices):
    rows = []
    for i in indices:
        pixels = ", ".join(fmt(v) for v in x[i])
        predicted = int(clf.predict(x[i : i + 1])[0])
        rows.append(f"    {{ label = {y[i]}, predicted = {predicted}, pixels = [{pixels}] }},")
    return rows


lines = [
    "# GENERATED by models/make_digits.py: 8x8 digits streamed to the",
    "# realistic neurons of demos/digits_transfer.ncl, pixels in [0, 1],",
    "# row-major, with their labels and digits_mlp's answers. `train` and",
    "# `test` share no images.",
    "{",
    f"  hidden_max = {hidden_max:.4g},",
    "  train = [",
    *stream(order[:STREAM_TRAIN]),
    "  ],",
    "  test = [",
    *stream(order[STREAM_TRAIN : STREAM_TRAIN + STREAM_TEST]),
    "  ],",
    "}",
]
(OUT / "digit_stream.ncl").write_text("\n".join(lines) + "\n")
print(f"wrote digit_stream.ncl (hidden max {hidden_max:.3g})")
