"""Prepare the MNIST demo's model and sample digits.

    uv run --with onnx --with numpy python -I models/make_mnist.py

Input: models/mnist-12.onnx, the MNIST CNN from the ONNX model zoo
(https://github.com/onnx/models, validated/vision/classification/mnist,
MIT license), unmodified. It reads a [1, 1, 28, 28] image, white digit on
black, pixels 0-255, and outputs 10 logits.

Writes:

- models/mnist_softmax.onnx: the same graph with a Softmax appended, so the
  outputs are probabilities.
- models/mnist_samples.ncl: the first two images of each digit in the MNIST
  test set, as ASCII art. The test set is downloaded once (about 1.6 MB,
  from PyTorch's mirror) into ~/.cache/nb-lib-mnist and checked by hash.

Deterministic; rerun after editing and commit the outputs.
"""

import gzip
import hashlib
import pathlib
import urllib.request

import numpy as np
import onnx
from onnx import helper
from onnx.reference import ReferenceEvaluator

OUT = pathlib.Path(__file__).resolve().parent
SAMPLES_PER_DIGIT = 2
# Characters for pixel levels 0, 85, 170, 255; the demo maps them back.
LEVELS = ".-+#"

model = onnx.load(OUT / "mnist-12.onnx")
graph = model.graph
(logits,) = graph.output
graph.node.append(helper.make_node("Softmax", [logits.name], ["probs"], name="probs", axis=1))
graph.output.remove(logits)
graph.output.append(helper.make_tensor_value_info("probs", onnx.TensorProto.FLOAT, [1, 10]))
onnx.checker.check_model(model, full_check=True)
onnx.save(model, OUT / "mnist_softmax.onnx")
ref = ReferenceEvaluator(model)


MIRROR = "https://ossci-datasets.s3.amazonaws.com/mnist/"
FILES = {
    "t10k-images-idx3-ubyte.gz": "8d422c7b0a1c1c79245a5bcf07fe86e33eeafee792b84584aec276f5a2dbc4e6",
    "t10k-labels-idx1-ubyte.gz": "f7ae60f92e00ec6debd23a6088c31dbd2371eca3ffa0defaefb259924204aec6",
}
CACHE = pathlib.Path.home() / ".cache" / "nb-lib-mnist"


def fetch(name):
    path = CACHE / name
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(MIRROR + name, path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != FILES[name]:
        raise SystemExit(f"{path}: unexpected sha256 {digest}")
    return gzip.decompress(path.read_bytes())


images = np.frombuffer(fetch("t10k-images-idx3-ubyte.gz"), np.uint8, offset=16).reshape(-1, 28, 28)
labels = np.frombuffer(fetch("t10k-labels-idx1-ubyte.gz"), np.uint8, offset=8)
held = [i for d in range(10) for i in np.flatnonzero(labels == d)[:SAMPLES_PER_DIGIT]]

entries, correct = [], 0
for i in held:
    levels = np.round(images[i] / 255 * (len(LEVELS) - 1)).astype(int)
    pixels = (levels * 255 / (len(LEVELS) - 1)).astype(np.float32)[None, None]
    (probs,) = ref.run(None, {graph.input[0].name: pixels})
    predicted = int(probs.argmax())
    label = int(labels[i])
    correct += predicted == label
    art = "\n".join("      " + "".join(LEVELS[v] for v in row) for row in levels)
    entries.append(f'  {{\n    label = {label},\n    predicted = {predicted},\n    art = m%"\n{art}\n    "%,\n  }},')
print(f"{correct}/{len(held)} samples classified correctly")

header = [
    "# GENERATED by models/make_mnist.py: MNIST test-set digits as ASCII art",
    "# (. - + # are pixel levels 0, 85, 170, 255, rounded from the originals),",
    "# with their labels and what mnist_softmax.onnx predicts for them.",
]
(OUT / "mnist_samples.ncl").write_text("\n".join(header + ["["] + entries + ["]"]) + "\n")
