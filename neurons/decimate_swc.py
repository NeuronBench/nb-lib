"""Decimate an SWC morphology into an nb-lib neuron.

    python3 -I neurons/decimate_swc.py neurons/swc/<cell>.swc neurons/<name>.ncl [fraction]

Keeps the soma, every branch point and every tip, and thins each unbranched
run between them evenly so the cell keeps about `fraction` (default 0.1) of
its points. Kept points are renumbered 1..n in depth-first order from the
soma, so ids are stable for a given input and fraction; each kept point's
parent is its nearest kept ancestor. Deterministic; rerun after editing and
commit the output.
"""

import math
import pathlib
import sys

src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
fraction = float(sys.argv[3]) if len(sys.argv) > 3 else 0.1

rows = {}
children = {}
header = []
for line in src.read_text().splitlines():
    if line.startswith("#"):
        header.append(line[1:].strip())
        continue
    if not line.strip():
        continue
    i, t, x, y, z, r, p = line.split()[:7]
    rows[int(i)] = (int(t), float(x), float(y), float(z), float(r), int(p))
    children.setdefault(int(p), []).append(int(i))
root = next(i for i, row in rows.items() if row[5] == -1)


def walk_runs(start):
    """Unbranched runs: (first node after a kept node, ..., next kept node)."""
    stack = [start]
    while stack:
        node = stack.pop()
        for child in sorted(children.get(node, [])):
            run = [child]
            while len(children.get(run[-1], [])) == 1 and rows[run[-1]][0] != 1:
                run.append(children[run[-1]][0])
            yield node, run
            stack.append(run[-1])


runs = list(walk_runs(root))
structural = 1 + len(runs)  # the soma, plus each run's end (a branch point or tip)
budget = max(structural, round(len(rows) * fraction))
interior = sum(len(run) - 1 for _, run in runs)
# Keep interior points at an even stride so the total meets the budget.
stride = max(1, math.ceil(interior / max(1, budget - structural))) if budget > structural else None

kept_parent = {root: -1}
for start, run in runs:
    parent = start
    for k, node in enumerate(run):
        last = k == len(run) - 1
        if last or (stride and (k + 1) % stride == 0):
            kept_parent[node] = parent
            parent = node

# Renumber depth-first from the soma.
kept_children = {}
for node, parent in kept_parent.items():
    kept_children.setdefault(parent, []).append(node)
order, stack = [], [root]
while stack:
    node = stack.pop()
    order.append(node)
    stack.extend(sorted(kept_children.get(node, []), reverse=True))
new_id = {node: i + 1 for i, node in enumerate(order)}

lines = [
    f"# GENERATED by neurons/decimate_swc.py from {src.name}: {len(order)} of",
    f"# {len(rows)} points (soma, branch points and tips kept). SWC columns: id, x,",
    "# y, z, r, type, parent. The `type` column indexes the membrane list in",
    "# default_swc_neuron.ncl.",
    'let default_swc_neuron = import "../default_swc_neuron.ncl" in',
    "default_swc_neuron",
    "[",
]
for node in order:
    t, x, y, z, r, _ = rows[node]
    parent = kept_parent[node]
    lines.append(
        f"  {{ id = {new_id[node]}, x = {x:.4f}, y = {y:.4f}, z = {z:.4f}, r = {r:.4f}, "
        f"type = {t}, parent = {new_id.get(parent, -1)} }},"
    )
lines.append("]")
out.write_text("\n".join(lines) + "\n")
print(f"{out}: {len(order)} of {len(rows)} points")
